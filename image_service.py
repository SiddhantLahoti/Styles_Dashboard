def get_cropped_image_bytes(image_path: Path, full_resolution: bool = False, tolerance: int = 15) -> bytes:
    """
    - full_resolution=True: Returns the original uncompressed image (PNG) with whitespace cropped
      for crisp stretching without JPEG compression artifacts.
    - full_resolution=False: High-quality thumbnail for fast card loading.
    """
    suffix = "_full.png" if full_resolution else "_thumb.jpg"
    cache_file = Path(IMAGE_CACHE_DIR) / f"{image_path.stem}{suffix}"

    if cache_file.exists():
        return cache_file.read_bytes()

    with PILImage.open(image_path) as pil_img:
        # Preserve transparency or clean white background
        if pil_img.mode in ("RGBA", "LA") or (pil_img.mode == "P" and "transparency" in pil_img.info):
            bg = PILImage.new("RGB", pil_img.size, (255, 255, 255))
            pil_img = pil_img.convert("RGBA")
            bg.paste(pil_img, mask=pil_img.split()[3])
            img_rgb = bg
        else:
            img_rgb = pil_img.convert("RGB")

        # Crop excess whitespace border
        bg_diff = PILImage.new("RGB", img_rgb.size, (255, 255, 255))
        diff = ImageChops.difference(img_rgb, bg_diff).convert("L")
        bbox = diff.point(lambda p: 255 if p > tolerance else 0).getbbox()
        cropped = img_rgb.crop(bbox) if bbox else img_rgb

        stream = io.BytesIO()

        if full_resolution:
            # Save as lossless PNG so fine lines and text stay sharp
            cropped.save(stream, format="PNG", optimize=True)
        else:
            # Fast high-DPI thumbnail for cards
            cropped.thumbnail((800, 800), PILImage.Resampling.LANCZOS)
            cropped.save(stream, format="JPEG", quality=90, optimize=True)

        data = stream.getvalue()

        try:
            cache_file.write_bytes(data)
        except Exception:
            pass

        return data


def generate_shortlist_excel(items: List[dict]) -> io.BytesIO:
    """
    Creates an Excel spreadsheet containing all columns (A-L) + Column M with the inserted image.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Shortlisted Items"

    headers = [
        "drcd", "DmCtg", "DmSalCtg", "Pdesc", "dmcrdt", 
        "DiaQty", "DiaCts", "CSQty", "Cscts", "Gldwt", "Silwt", "Customer", "Image"
    ]
    ws.append(headers)

    # Styling dimensions
    ws.column_dimensions["M"].width = 24
    row_height = 80
    max_w, max_h = 140, 100

    for idx, item in enumerate(items, start=2):
        ws.row_dimensions[idx].height = row_height
        ws.append([
            item.get("drcd", ""),
            item.get("DmCtg", ""),
            item.get("DmSalCtg", ""),
            item.get("Pdesc", ""),
            str(item.get("dmcrdt", "")),
            item.get("DiaQty", 0),
            item.get("DiaCts", 0),
            item.get("CSQty", 0),
            item.get("Cscts", 0),
            item.get("Gldwt", 0),
            item.get("Silwt", 0),
            item.get("Customer", "")
        ])

        # Find and attach image in Column M (13th column)
        code = str(item.get("drcd", ""))
        img_path = find_image_for_style(code)
        if img_path:
            try:
                img_data = get_cropped_image_bytes(img_path, full_resolution=False)
                img_stream = io.BytesIO(img_data)
                excel_img = ExcelImage(img_stream)

                scale = min(max_w / excel_img.width, max_h / excel_img.height)
                excel_img.width = int(excel_img.width * scale)
                excel_img.height = int(excel_img.height * scale)

                # Center image in cell
                cell_w_px = 168
                cell_h_px = int(row_height * 96 / 72)
                off_x = max(0, int((cell_w_px - excel_img.width) / 2))
                off_y = max(0, int((cell_h_px - excel_img.height) / 2))

                _from = ssd.AnchorMarker(
                    col=12, colOff=ssd.pixels_to_EMU(off_x),
                    row=idx - 1, rowOff=ssd.pixels_to_EMU(off_y)
                )
                to = ssd.AnchorMarker(
                    col=12, colOff=ssd.pixels_to_EMU(off_x + excel_img.width),
                    row=idx - 1, rowOff=ssd.pixels_to_EMU(off_y + excel_img.height)
                )
                excel_img.anchor = ssd.TwoCellAnchor(editAs="twoCell", _from=_from, to=to)
                ws.add_image(excel_img)
            except Exception as e:
                print(f"[WARNING] Could not insert image for {code}: {e}")

    out = io.BytesIO()
    wb.save(out)
    out.seek(0)
    return out

def generate_catalogue_excel(items: List[dict], per_row: int = 4) -> io.BytesIO:
    """
    Generates an Excel workbook formatted in Catalogue Card Grid view matching TEST.xlsx.
    per_row can be 3, 4, or 5.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Catalogue"
    ws.views.sheetView[0].showGridLines = True

    # Styling definitions matching TEST.xlsx
    font_header = Font(name="Arial Rounded MT Bold", size=16, bold=True)
    font_card = Font(name="Aptos Narrow", size=11)
    
    fill_h1 = PatternFill(start_color="FFFFF0F5", end_color="FFFFF0F5", fill_type="solid")
    fill_h2 = PatternFill(start_color="FFEEEEE0", end_color="FFEEEEE0", fill_type="solid")

    thin_border = Side(style="thin", color="000000")
    thick_border = Side(style="thick", color="000000")


    # Set exact column widths matching reference file (all 13.0)
    total_cols = 1 + (per_row * 3)
    ws.column_dimensions['A'].width = 13.0
    for c in range(2, total_cols + 1):
        ws.column_dimensions[get_column_letter(c)].width = 13.0

    # Set exact header row heights matching reference file
    last_col_letter = get_column_letter(total_cols)
    ws.row_dimensions[1].height = 15.75
    ws.row_dimensions[2].height = 39.95
    ws.row_dimensions[3].height = 30.0

    ws.merge_cells(f"B2:{last_col_letter}2")
    cell_b2 = ws["B2"]
    cell_b2.value = "INTER GOLD (INDIA) PVT. LTD."
    cell_b2.font = font_header
    cell_b2.alignment = Alignment(horizontal="center", vertical="center")
    cell_b2.fill = fill_h1

    ws.merge_cells(f"B3:{last_col_letter}3")
    cell_b3 = ws["B3"]
    cell_b3.value = "Collection"
    cell_b3.font = font_header
    cell_b3.alignment = Alignment(horizontal="center", vertical="center")
    cell_b3.fill = fill_h2

    # Render product cards in grid
    start_row = 4
    image_rows_count = 9
    block_total_rows = 11  # 9 rows image + 1 row Style # + 1 row Dia Wt.

    for idx, item in enumerate(items):
        grid_row = idx // per_row
        grid_col = idx % per_row

        r_top = start_row + (grid_row * block_total_rows)
        r_bottom_img = r_top + image_rows_count - 1
        r_style = r_bottom_img + 1
        r_dia = r_style + 1

        c_start = 2 + (grid_col * 3)
        c_mid = c_start + 1
        c_end = c_start + 2

        col_start_letter = get_column_letter(c_start)
        col_mid_letter = get_column_letter(c_mid)
        col_end_letter = get_column_letter(c_end)

        # 1. Merge image area (3 columns x 9 rows)
        ws.merge_cells(f"{col_start_letter}{r_top}:{col_end_letter}{r_bottom_img}")

        # Apply borders to the image block
        for r in range(r_top, r_bottom_img + 1):
            for c in range(c_start, c_end + 1):
                cell = ws.cell(r, c)
                l = thick_border if c == c_start else None
                right = thin_border if c == c_end else None
                t = thin_border if r == r_top else None
                b = thin_border if r == r_bottom_img else None
                cell.border = Border(left=l, right=right, top=t, bottom=b)

        # 2. Row: Style #
        cell_style_lbl = ws.cell(r_style, c_start, "Style #")
        cell_style_lbl.font = font_card
        cell_style_lbl.border = Border(left=thick_border, right=thin_border, top=thin_border, bottom=thin_border)

        ws.merge_cells(f"{col_mid_letter}{r_style}:{col_end_letter}{r_style}")
        style_val = str(item.get("drcd", "")).strip()
        cell_style_val = ws.cell(r_style, c_mid, style_val)
        cell_style_val.font = font_card
        cell_style_val.alignment = Alignment(horizontal="center", vertical="center")
        for c in range(c_mid, c_end + 1):
            ws.cell(r_style, c).border = Border(left=thin_border, right=thin_border, top=thin_border, bottom=thin_border)

        # 3. Row: Dia Wt.
        cell_dia_lbl = ws.cell(r_dia, c_start, "Dia Wt.")
        cell_dia_lbl.font = font_card
        cell_dia_lbl.border = Border(left=thick_border, right=thin_border, top=thin_border, bottom=thin_border)

        ws.merge_cells(f"{col_mid_letter}{r_dia}:{col_end_letter}{r_dia}")
        dia_cts_val = item.get("DiaCts", 0)
        formatted_dia = f"{float(dia_cts_val):.2f} CT" if dia_cts_val else "0.00 CT"
        cell_dia_val = ws.cell(r_dia, c_mid, formatted_dia)
        cell_dia_val.font = font_card
        cell_dia_val.alignment = Alignment(horizontal="center", vertical="center")
        for c in range(c_mid, c_end + 1):
            ws.cell(r_dia, c).border = Border(left=thin_border, right=thin_border, top=thin_border, bottom=thin_border)

        # 4. Attach image with locked aspect ratio (no distortion or stretching)
        # 4. Attach image centered with natural aspect ratio & proper sizing
        img_path = find_image_for_style(style_val)
        if img_path:
            try:
                # Use high-quality image bytes
                img_data = get_cropped_image_bytes(img_path, full_resolution=False)
                excel_img = ExcelImage(io.BytesIO(img_data))

                # Card box bounds: 3 columns ≈ 285px wide, 9 rows ≈ 180px high
                max_w = 255
                max_h = 155

                # Scale proportionally so the image is never stretched
                scale = min(max_w / excel_img.width, max_h / excel_img.height)
                excel_img.width = int(excel_img.width * scale)
                excel_img.height = int(excel_img.height * scale)

                # Calculate center offsets within the 285px x 180px cell area
                off_x = max(0, int((285 - excel_img.width) / 2))
                off_y = max(0, int((180 - excel_img.height) / 2))

                # Anchor cleanly using OneCellAnchor (top-left offset + explicit width & height)
                _from = ssd.AnchorMarker(
                    col=c_start - 1, 
                    colOff=ssd.pixels_to_EMU(off_x),
                    row=r_top - 1, 
                    rowOff=ssd.pixels_to_EMU(off_y)
                )
                ext = ssd.XDRPositiveSize2D(
                    ssd.pixels_to_EMU(excel_img.width), 
                    ssd.pixels_to_EMU(excel_img.height)
                )
                excel_img.anchor = ssd.OneCellAnchor(_from=_from, ext=ext)

                ws.add_image(excel_img)
            except Exception as e:
                print(f"[WARNING] Catalogue image error for {style_val}: {e}")

    out = io.BytesIO()
    wb.save(out)
    out.seek(0)
    return out